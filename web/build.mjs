/**
 * Bundles vgplot and the page into one ESM file the plugin can serve.
 *
 * BUILD TIME ONLY. Node is not needed to install or run the plugin: the
 * output is checked into the repository and the shipped zip carries a plain
 * .js file, loaded over the equis:// scheme that web_assets.py registers.
 * This exists because vgplot is published as npm packages with bare-specifier
 * imports, and a browser resolves URLs rather than package names - something
 * has to flatten the graph, and that something runs on Node.
 *
 *   npm install          # once, from the checked-in lockfile
 *   npm run build        # writes ../equis_loader/web/
 *   npm run check        # rebuilds to a temp dir and diffs; CI uses this
 *
 * `--check` is what makes "reproducible from a lockfile" a claim that can
 * fail rather than an aspiration: it rebuilds and compares byte for byte
 * against what is committed, so a bundle that drifted from its sources is
 * caught in CI instead of years later when nobody can rebuild it.
 */
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "src");
const OUT = resolve(HERE, "..", "equis_loader", "web");
const CHECK = process.argv.includes("--check");

async function bundleTo(outdir) {
  await mkdir(outdir, { recursive: true });
  await build({
    entryPoints: [join(SRC, "app.js")],
    outfile: join(outdir, "app.js"),
    bundle: true,
    format: "esm",
    platform: "browser",
    target: ["chrome120"],          // QGIS 4.2.1 reports Chromium 140
    minify: true,
    sourcemap: false,               // a 3 MB map in the plugin zip helps nobody
    legalComments: "none",
    // Deterministic: no timestamps, no absolute paths, nothing that differs
    // between two machines building the same commit.
    define: { "process.env.NODE_ENV": '"production"' },
    logLevel: "warning",
  });
  // The page itself is copied rather than bundled: it is HTML, and keeping
  // it readable in the plugin directory is worth more than shaving bytes.
  for (const name of await readdir(SRC)) {
    if (name.endsWith(".html") || name.endsWith(".css")) {
      await writeFile(join(outdir, name), await readFile(join(SRC, name)));
    }
  }
}

function digest(bytes) {
  return createHash("sha256").update(bytes).digest("hex").slice(0, 16);
}

async function manifest(dir) {
  const names = (await readdir(dir)).filter((n) => n !== "BUILD.json").sort();
  const entries = {};
  for (const name of names) {
    const bytes = await readFile(join(dir, name));
    entries[name] = { bytes: bytes.length, sha256: digest(bytes) };
  }
  return entries;
}

if (CHECK) {
  const temporary = join(HERE, ".check-out");
  await rm(temporary, { recursive: true, force: true });
  await bundleTo(temporary);
  const fresh = await manifest(temporary);
  if (!existsSync(OUT)) {
    console.error("No committed bundle at %s. Run `npm run build`.", OUT);
    process.exit(1);
  }
  const committed = await manifest(OUT);
  await rm(temporary, { recursive: true, force: true });
  const names = new Set([...Object.keys(fresh), ...Object.keys(committed)]);
  let drifted = false;
  for (const name of [...names].sort()) {
    const a = committed[name];
    const b = fresh[name];
    const same = a && b && a.sha256 === b.sha256;
    if (!same) drifted = true;
    console.log(
      "%s %s  committed=%s rebuilt=%s",
      same ? "ok  " : "DIFF",
      name.padEnd(14),
      a ? a.sha256 : "absent",
      b ? b.sha256 : "absent",
    );
  }
  if (drifted) {
    console.error(
      "\nThe committed bundle does not match a rebuild from these sources.\n" +
      "Run `npm run build` and commit the result.",
    );
    process.exit(1);
  }
  console.log("\nThe committed bundle matches a rebuild from the lockfile.");
} else {
  await rm(OUT, { recursive: true, force: true });
  await bundleTo(OUT);
  const entries = await manifest(OUT);
  const pkg = JSON.parse(await readFile(join(HERE, "package.json"), "utf8"));
  await writeFile(
    join(OUT, "BUILD.json"),
    JSON.stringify(
      {
        note: "Generated by web/build.mjs. Do not edit. Rebuild with " +
              "`cd web && npm ci && npm run build`.",
        versions: pkg.devDependencies,
        files: entries,
      },
      null,
      1,
    ) + "\n",
  );
  for (const [name, info] of Object.entries(entries)) {
    console.log(`${name.padEnd(14)} ${(info.bytes / 1024).toFixed(1).padStart(8)} KB  ${info.sha256}`);
  }
  console.log("\nwrote %s", OUT);
}

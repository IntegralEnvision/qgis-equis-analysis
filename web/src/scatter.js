/**
 * US-24: a scatter of two analytes, one point per SAMPLE.
 *
 * The decisions, kept here and testable without a browser; scatterplot.js
 * is the vgplot wiring around them. The data is a pivot table built by
 * equis_loader/pivot.py - one row per normal sample, four columns per
 * analyte (`<p>_value`, `<p>_detect`, `<p>_qualifier`, `<p>_detectlimit`).
 * See docs/pivot-design.md for every rule below and the measurement behind
 * it.
 *
 * WHAT THIS REFUSES TO DO, because each produces a plausible picture rather
 * than an error:
 *
 *   * Plot a point for a sample missing either analyte. A scatter point is
 *     a co-occurrence; a sample measured for one analyte has none. Counted
 *     and stated as unpaired, never drawn at an invented value.
 *   * Infer detection. `_detect` is DETECT_FLAG as the database recorded
 *     it; which values mean "detected" comes from the host (DETECT_TRUE in
 *     store.py), not from a list written here. A blank flag is UNKNOWN, not
 *     a non-detect: counted, and left out of the four classes.
 *   * Hide the non-detects. Four classes, four symbols, every one drawn
 *     (decided 2026-10-08). A non-detect sits at its limit, so they stack -
 *     41,821 of the 63,222 Mn x Pb samples in WS/T land on 19 limit pairs -
 *     and that is understood: the symbol says what they are.
 */

/** The four detection classes, in drawing order (rarest last, on top). */
export const CLASSES = [
  { key: "neither", symbol: "times", filled: false, color: "#8c8c8c" },
  { key: "x_only", symbol: "triangle", filled: false, color: "#e07b28" },
  { key: "y_only", symbol: "square", filled: false, color: "#3f9b4f" },
  { key: "both", symbol: "circle", filled: true, color: "#2f6fb0" },
];

/** Each class's mark as a character, so the caption can be the legend. */
export const GLYPHS = { circle: "●", triangle: "△", square: "□", times: "×" };

const glyphFor = (key) => GLYPHS[(CLASSES.find((c) => c.key === key) || {}).symbol] || "•";

/** What each class means, in words, for the legend and the caption. */
export function classLabel(key, xName, yName) {
  switch (key) {
    case "both": return `both detected`;
    case "x_only": return `${xName} detected, ${yName} not`;
    case "y_only": return `${yName} detected, ${xName} not`;
    case "neither": return `neither detected (both at limits)`;
    default: return key;
  }
}

const quote = (text) => `'${String(text).replace(/'/g, "''")}'`;

/** A pivot column name is generated by pivot.py, but it travels through
 *  JSON and into SQL, so it is checked rather than trusted. */
function column(prefix, suffix) {
  if (!/^[a-z][a-z0-9_]*$/.test(prefix)) {
    throw new Error(`not a pivot column prefix: ${prefix}`);
  }
  return `${prefix}_${suffix}`;
}

// A pivot (p_) or a pair taken from one (pp_, pivot.pair_table) - the
// only names the host makes, and so the only ones put into SQL here.
function table(name) {
  if (!/^pp?_[a-z0-9_]+$/.test(name)) {
    throw new Error(`not a pivot table: ${name}`);
  }
  return name;
}

// The host's table of samples to draw solid (analysis.solid_table).
function solidTable(name) {
  if (!/^ps_[0-9]+$/.test(String(name))) {
    throw new Error(`not a solid-samples table: ${name}`);
  }
  return name;
}

/**
 * What the points are, for the caption's first line. Every sample, all
 * time: "63,222 samples carrying both, one point each" as before.
 * Otherwise the count drawn, what each point is, out of how many, and
 * the window: "219 points, each location's most recent sample (of 63,222
 * samples) · 2015-01-01 to 2020-12-31".
 */
export function pointsPhrase(drawn, points = null, all = null, carrying = "both") {
  const n = (v) => Number(v || 0).toLocaleString("en-US");
  const mode = (points || {}).mode || "all";
  const window = (points || {}).window;
  let text = mode === "all"
    ? `${n(drawn)} samples carrying ${carrying}${window ? " in the window" : ", one point each"}`
    : `${n(drawn)} points, ${points.label}`;
  if ((mode !== "all" || window) && all !== null && all !== undefined) {
    text += ` (of ${n(all)} samples)`;
  }
  if (Array.isArray(window)) {
    text += ` · ${window[0] || "…"} to ${window[1] || "…"}`;
  }
  return text;
}

/**
 * The map's selection as a predicate on `location`, or null for none. An
 * empty ARRAY is "these zero locations", FALSE, not "no filter" - the US-6
 * rule. Case-insensitive: the report and the feature service do not agree
 * on case (CLAUDE.md). Shared by the SQL here and the map's clause on the
 * linked views' crossfilter (linked.js), so the two cannot disagree.
 */
export function locationsSql(locations) {
  if (!Array.isArray(locations)) return null;
  if (!locations.length) return "FALSE";
  return `upper(coalesce(location, '')) IN (${locations
    .map((code) => quote(String(code).toUpperCase())).join(", ")})`;
}

/**
 * The SQL behind the scatter: one row per sample carrying both analytes and
 * a known detection state for each, with its class.
 *
 *  - `pivot`      the pivot table's name
 *  - `x`, `y`     column prefixes in that table
 *  - `detectTrue` the flag values meaning detected, from the host
 *  - `locations`  the map's selection, or null for none. An empty ARRAY is
 *                 "these zero locations", not "no filter" - the US-6 rule.
 */
export function scatterSql({ pivot, x, y, detectTrue, locations = null,
                             bivariate = null, logX = false, logY = false,
                             solid = null }) {
  if (!Array.isArray(detectTrue) || !detectTrue.length) {
    throw new Error("scatterSql needs the host's detect-true values");
  }
  const t = table(pivot);
  const truth = `(${detectTrue.map((v) => quote(String(v).toUpperCase())).join(", ")})`;
  const xd = `upper(${column(x, "detect")}) IN ${truth}`;
  const yd = `upper(${column(y, "detect")}) IN ${truth}`;
  const where = [
    `${column(x, "value")} IS NOT NULL`,
    `${column(y, "value")} IS NOT NULL`,
    `${column(x, "detect")} IS NOT NULL`,
    `${column(y, "detect")} IS NOT NULL`,
  ];
  // A log axis cannot place zero or below. Such points are left OUT of the
  // drawing - and named in the caption (excludedSql) - rather than forcing
  // the axis linear: at Facility A, two As values reported as a DETECTED 0
  // flattened 834 good points onto a linear axis (2026-10-09).
  if (logX) where.push(`${column(x, "value")} > 0`);
  if (logY) where.push(`${column(y, "value")} > 0`);
  // The points mode and the time window (decided 2026-10-12): the host
  // picks the samples to draw solid - one real sample per location, or
  // every sample in the window - and names them in a table. The rule
  // lives there (bivariate.picks_sql), not here.
  if (solid) where.push(`sample IN (SELECT sample FROM ${solidTable(solid)})`);
  const located = locationsSql(locations);
  if (located) where.push(located);
  return `SELECT sample, location, sample_date,
                 ${column(x, "value")} AS x, ${column(y, "value")} AS y,
                 ${column(x, "qualifier")} AS x_qualifier,
                 ${column(y, "qualifier")} AS y_qualifier,
                 CASE WHEN ${xd} AND ${yd} THEN 'both'
                      WHEN ${xd} THEN 'x_only'
                      WHEN ${yd} THEN 'y_only'
                      ELSE 'neither' END AS class,
                 ${colourSql(column(x, "value"), column(y, "value"), xd, yd, bivariate)} AS colour
          FROM ${t}
          WHERE ${where.join(" AND ")}`;
}

/**
 * Each point's colour, from the HOST's breaks and palette (bivariate.py),
 * never decided here: the map layer is coloured from the same answers, so
 * a point and its station cannot disagree. A sample detected on both axes
 * takes the "x-y" class colour; anything involving a non-detect is grey
 * (decided 2026-10-09). A break is INSIDE its class (<=), as in class_of.
 */
export function colourSql(xv, yv, xd, yd, bivariate) {
  if (!bivariate || !bivariate.palette) return "NULL";
  const grey = quote(bivariate.grey || "#9a9a9a");
  const xb = ((bivariate.x || {}).breaks || []).map(Number);
  const yb = ((bivariate.y || {}).breaks || []).map(Number);
  if (xb.length !== 2 || yb.length !== 2 || ![...xb, ...yb].every(Number.isFinite)) {
    return grey;
  }
  const cls = (col, b) =>
    `CASE WHEN ${col} <= ${b[0]} THEN 1 WHEN ${col} <= ${b[1]} THEN 2 ELSE 3 END`;
  const cases = [];
  for (const [key, hex] of Object.entries(bivariate.palette)) {
    const [xc, yc] = key.split("-").map(Number);
    if (!/^#[0-9a-fA-F]{6}$/.test(hex) || !xc || !yc) continue;
    cases.push(`WHEN ${cls(xv, xb)} = ${xc} AND ${cls(yv, yb)} = ${yc} THEN ${quote(hex)}`);
  }
  return `CASE WHEN NOT (${xd} AND ${yd}) THEN ${grey} ${cases.join(" ")} ELSE ${grey} END`;
}

/** The break values as legend text: "<= 76.1 | 76.1-810 | > 810". */
export function breakLabels(breaks) {
  // Three significant figures, by the locale formatter - NOT by trimming
  // "0"s off a string, which turns 810 into 81.
  const fmt = (v) => Number(v).toLocaleString("en-US", { maximumSignificantDigits: 3 });
  if (!breaks || breaks.length !== 2) return ["", "", ""];
  return [`≤ ${fmt(breaks[0])}`, `${fmt(breaks[0])}–${fmt(breaks[1])}`,
          `> ${fmt(breaks[1])}`];
}

/**
 * The counts a caption must state, as one query: how many samples fall in
 * each class, and how many could NOT be drawn and why.
 */
export function scatterCountsSql({ pivot, x, y, detectTrue }) {
  const t = table(pivot);
  const truth = `(${detectTrue.map((v) => quote(String(v).toUpperCase())).join(", ")})`;
  const xv = column(x, "value");
  const yv = column(y, "value");
  const xdc = column(x, "detect");
  const ydc = column(y, "detect");
  const paired = `${xv} IS NOT NULL AND ${yv} IS NOT NULL`;
  const known = `${xdc} IS NOT NULL AND ${ydc} IS NOT NULL`;
  const xd = `upper(${xdc}) IN ${truth}`;
  const yd = `upper(${ydc}) IN ${truth}`;
  return `SELECT
      count(*) FILTER (WHERE ${paired} AND ${known} AND ${xd} AND ${yd}) AS both,
      count(*) FILTER (WHERE ${paired} AND ${known} AND ${xd} AND NOT ${yd}) AS x_only,
      count(*) FILTER (WHERE ${paired} AND ${known} AND NOT ${xd} AND ${yd}) AS y_only,
      count(*) FILTER (WHERE ${paired} AND ${known} AND NOT ${xd} AND NOT ${yd}) AS neither,
      count(*) FILTER (WHERE ${paired} AND NOT (${known})) AS unknown,
      count(*) FILTER (WHERE NOT (${paired})) AS unpaired,
      min(${xv}) FILTER (WHERE ${paired} AND ${known} AND ${xv} > 0) AS x_min,
      min(${yv}) FILTER (WHERE ${paired} AND ${known} AND ${yv} > 0) AS y_min,
      count(*) FILTER (WHERE ${paired} AND ${known} AND ${xv} <= 0) AS x_nonpositive,
      count(*) FILTER (WHERE ${paired} AND ${known} AND ${yv} <= 0) AS y_nonpositive,
      count(*) FILTER (WHERE ${paired} AND ${known} AND (${xv} <= 0 OR ${yv} <= 0)) AS nonpositive
    FROM ${t}`;
}

/**
 * Log whenever the axis has positive values; linear only when it has none.
 * Concentrations span orders of magnitude - one Mn series runs 0.05 to
 * 936,000 - so a linear axis puts nearly every point in a corner. Values of
 * zero or below cannot sit on a log axis; they are left out of the drawing
 * and NAMED (excludedSql, scatterCaption), never allowed to flatten the
 * rest. Changed 2026-10-09 from "any zero makes it linear", after two
 * detected-0 As values did exactly that to 834 points.
 */
export function axisType(positiveMinimum) {
  return positiveMinimum !== null && positiveMinimum !== undefined
    && Number(positiveMinimum) > 0 ? "log" : "linear";
}

/** The samples a log axis leaves out, for the caption to name. */
export function excludedSql(base, logX, logY, limit = 5) {
  const conds = [];
  if (logX) conds.push("x <= 0");
  if (logY) conds.push("y <= 0");
  if (!conds.length) return null;
  return `SELECT sample, x, y, class FROM (${scatterSql({ ...base, logX: false,
    logY: false })}) WHERE ${conds.join(" OR ")} ORDER BY sample LIMIT ${Number(limit)}`;
}

/** "Manganese (T, ug/L)" - the unit is on the axis, always (US-15). */
export function axisLabel(meta) {
  const parts = [meta.fraction, meta.unit || "unit not reported"]
    .filter((part) => part);
  return `${meta.chemical} (${parts.join(", ")})`;
}

/** The caption: the population, every class, and what was NOT drawn. */
export function scatterCaption({ x, y, matrix = null, counts, resolved = 0,
                                 excluded = null, pivotExcluded = null,
                                 points = null, allSamples = null }) {
  const n = (v) => Number(v || 0).toLocaleString("en-US");
  const drawn = ["both", "x_only", "y_only", "neither"]
    .reduce((sum, key) => sum + Number(counts[key] || 0), 0);
  const lines = [
    `${x.chemical} vs ${y.chemical}${matrix ? " · " + matrix : ""}`
      + ` · ${pointsPhrase(drawn, points, allSamples)}`,
    // The legend too: each class with its mark, once. It was printed twice,
    // in a legend and here, and space above the fold is short (2026-10-12).
    ["both", "x_only", "y_only", "neither"]
      .map((key) => `${glyphFor(key)} ${classLabel(key, x.chemical, y.chemical)}`
        + ` ${n(counts[key])}`)
      .join(" · "),
  ];
  const left = [];
  if (Number(counts.unpaired)) {
    left.push(`${n(counts.unpaired)} samples carry only one of the two`);
  }
  if (Number(counts.unknown)) {
    left.push(`${n(counts.unknown)} have a blank detect flag`);
  }
  if (pivotExcluded && Number(pivotExcluded.field_replicates)) {
    // Not plotted by decision (2026-10-09); the primary of each is.
    left.push(`${n(pivotExcluded.field_replicates)} field duplicates and `
      + "replicates (recognised by code; each one's primary sample is plotted)");
  }
  if (pivotExcluded && Number(pivotExcluded.qc_rows)) {
    left.push(`${n(pivotExcluded.qc_rows)} QC results (blanks, duplicates)`);
  }
  if (left.length) lines.push(`Not drawn: ${left.join("; ")}.`);
  if (excluded && Number(excluded.count)) {
    const det = (cls, axis) => (axis === "x" ? ["both", "x_only"] : ["both", "y_only"])
      .includes(cls) ? "reported as detected" : "a non-detect";
    const named = (excluded.samples || []).map((s) => {
      const parts = [];
      if (excluded.logX && Number(s.x) <= 0) parts.push(`${x.chemical} ${s.x} (${det(s.class, "x")})`);
      if (excluded.logY && Number(s.y) <= 0) parts.push(`${y.chemical} ${s.y} (${det(s.class, "y")})`);
      return `${s.sample}: ${parts.join(", ")}`;
    });
    const more = Number(excluded.count) - named.length;
    lines.push(`Not on the log axes: ${n(excluded.count)} sample`
      + `${Number(excluded.count) === 1 ? "" : "s"} with a value of 0 or below`
      + ` - ${named.join("; ")}${more > 0 ? `; and ${n(more)} more` : ""}.`);
  }
  if (Number(resolved)) {
    lines.push(`${n(resolved)} cells had several results and kept one: `
      + "initial over replicate, detected over non-detect, then higher.");
  }
  return lines;
}

/**
 * What a brush rectangle selects: samples, their locations, and the codes
 * the map highlights. Over the SHOWN view, which already carries the map's
 * selection, so a brush and a map selection compose as an intersection.
 */
export function brushSql(view, box) {
  // A scatter's view (sv_) or a ternary's (tv_): both carry x and y.
  if (!/^[st]v_[0-9]+_shown$/.test(view)) throw new Error(`not a chart view: ${view}`);
  const n = (v) => {
    const num = Number(v);
    if (!Number.isFinite(num)) throw new Error(`not a number: ${v}`);
    return num;
  };
  return `SELECT count(*) AS samples, count(DISTINCT location) AS locations,
                 list(DISTINCT location) AS codes
          FROM ${view}
          WHERE x BETWEEN ${n(box.x0)} AND ${n(box.x1)}
            AND y BETWEEN ${n(box.y0)} AND ${n(box.y1)}`;
}

/** The brush, in words: how many samples, at how many locations. */
export function scatterBrushLabel({ samples = null, locations = null, total }) {
  const n = (v) => Number(v || 0).toLocaleString("en-US");
  if (samples === null) return `Drag a rectangle to select samples (${n(total)} drawn).`;
  return `${n(samples)} of ${n(total)} samples selected, at ${n(locations)} `
    + `location${Number(locations) === 1 ? "" : "s"}.`;
}
